// Requirement ↔ test-case ↔ spec traceability.
//
//   pnpm coverage:check          → verify, exit 1 on any gap
//   pnpm coverage:check --write  → verify and regenerate docs/traceability-matrix.md
//
// Reads docs/requirements.md (REQ-… rows), test-cases/*.md (### TC-… blocks)
// and every spec under tests/ (@TC-… tags). See docs/conventions.md.

import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(__dirname, "..");
const rel = (p: string) => path.relative(ROOT, p).replace(/\\/g, "/");

interface Req {
  id: string;
  text: string;
  module: string;
}
interface Tc {
  id: string;
  title: string;
  reqs: string[];
  automated: string | null; // path, or null when manual
  manualReason: string | null;
  file: string;
  layer: string;
  priority: string;
}

function walk(dir: string, filter: (f: string) => boolean): string[] {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p, filter) : filter(p) ? [p] : [];
  });
}

function readRequirements(): Req[] {
  const md = fs.readFileSync(path.join(ROOT, "docs/requirements.md"), "utf8");
  const reqs: Req[] = [];
  let module = "";
  for (const line of md.split(/\r?\n/)) {
    const h = /^## ([A-Z]+) —/.exec(line);
    if (h) module = h[1];
    const row = /^\|\s*(REQ-[A-Z]+-\d+)\s*\|\s*(.+?)\s*\|\s*$/.exec(line);
    if (row) reqs.push({ id: row[1], text: row[2], module });
  }
  return reqs;
}

function readTestCases(): Tc[] {
  const files = walk(path.join(ROOT, "test-cases"), (f) => f.endsWith(".md"));
  const out: Tc[] = [];
  for (const file of files) {
    const md = fs.readFileSync(file, "utf8");
    const blocks = md
      .split(/^(?=### TC-)/m)
      .filter((b) => b.startsWith("### TC-"));
    for (const b of blocks) {
      const head = /^### (TC-[A-Z]+-\d+)\s+[—-]\s+(.+)$/m.exec(b);
      if (!head) continue;
      const reqLine = /\*\*Requirements?:\*\*\s*(.+)$/m.exec(b)?.[1] ?? "";
      const autoLine = /\*\*Automated:\*\*\s*(.+)$/m.exec(b)?.[1]?.trim() ?? "";
      const pathMatch = /`([^`]+\.(?:e2e|api)\.ts)`/.exec(autoLine);
      const layer = /\*\*Layer:\*\*\s*([a-z0-9-]+)/i.exec(b)?.[1] ?? "";
      const priority = /\*\*Priority:\*\*\s*(P\d)/.exec(b)?.[1] ?? "";
      out.push({
        id: head[1],
        title: head[2].trim(),
        reqs: reqLine.match(/REQ-[A-Z]+-\d+/g) ?? [],
        automated: pathMatch ? pathMatch[1] : null,
        manualReason: pathMatch ? null : autoLine || null,
        file: rel(file),
        layer,
        priority
      });
    }
  }
  return out;
}

function readSpecTags(): Map<string, Set<string>> {
  // TC id → spec files tagging it
  const specs = walk(path.join(ROOT, "tests"), (f) =>
    /\.(e2e|api)\.ts$/.test(f)
  );
  const tags = new Map<string, Set<string>>();
  for (const f of specs) {
    const src = fs.readFileSync(f, "utf8");
    for (const m of src.matchAll(/["'`]@(TC-[A-Z]+-\d+)["'`]/g)) {
      if (!tags.has(m[1])) tags.set(m[1], new Set());
      tags.get(m[1])!.add(rel(f));
    }
  }
  return tags;
}

const reqs = readRequirements();
const tcs = readTestCases();
const tags = readSpecTags();
const errors: string[] = [];

const reqIds = new Set(reqs.map((r) => r.id));
const tcIds = new Map<string, Tc>();
for (const tc of tcs) {
  if (tcIds.has(tc.id))
    errors.push(
      `${tc.id} defined twice (${tcIds.get(tc.id)!.file}, ${tc.file})`
    );
  tcIds.set(tc.id, tc);
  if (tc.reqs.length === 0) errors.push(`${tc.id} names no requirement`);
  for (const r of tc.reqs)
    if (!reqIds.has(r)) errors.push(`${tc.id} names unknown ${r}`);
  if (tc.automated) {
    if (!fs.existsSync(path.join(ROOT, tc.automated)))
      errors.push(`${tc.id} → missing file ${tc.automated}`);
    else if (!tags.get(tc.id)?.has(tc.automated))
      errors.push(`${tc.id} → ${tc.automated} has no test tagged @${tc.id}`);
  } else if (!tc.manualReason?.startsWith("manual")) {
    errors.push(`${tc.id} has no Automated path and no "manual — reason"`);
  }
}
for (const r of reqs) {
  if (!tcs.some((t) => t.reqs.includes(r.id)))
    errors.push(`${r.id} has no test case`);
}
for (const [id, files] of tags) {
  if (!tcIds.has(id))
    errors.push(
      `@${id} tagged in ${[...files].join(", ")} but defined in no test case`
    );
}

const automated = tcs.filter((t) => t.automated).length;
const manual = tcs.length - automated;
const coveredReqs = reqs.filter((r) =>
  tcs.some((t) => t.reqs.includes(r.id))
).length;

if (process.argv.includes("--write")) {
  const lines: string[] = [
    "# Traceability matrix",
    "",
    "Generated by `pnpm coverage:check --write` — do not edit by hand.",
    "",
    `**${reqs.length}** requirements · **${coveredReqs}** covered · **${tcs.length}** test cases (${automated} automated, ${manual} manual)`,
    "",
    "| Requirement | Test cases | Automated in |",
    "| --- | --- | --- |"
  ];
  for (const r of reqs) {
    const mine = tcs.filter((t) => t.reqs.includes(r.id));
    const files = [...new Set(mine.map((t) => t.automated ?? "manual"))];
    lines.push(
      `| **${r.id}** ${r.text.replace(/\|/g, "\\|")} | ${
        mine.map((t) => t.id).join(", ") || "⚠️ none"
      } | ${files.map((f) => (f === "manual" ? f : `\`${f}\``)).join("<br>") || "—"} |`
    );
  }
  lines.push("");
  fs.writeFileSync(
    path.join(ROOT, "docs/traceability-matrix.md"),
    lines.join("\n")
  );
  console.log("wrote docs/traceability-matrix.md");
}

console.log(
  `requirements ${coveredReqs}/${reqs.length} covered · test cases ${tcs.length} (${automated} automated, ${manual} manual) · tagged specs ${tags.size}`
);
if (errors.length) {
  console.error(`\n${errors.length} problem(s):`);
  for (const e of errors) console.error(`  - ${e}`);
  process.exit(1);
}
console.log("coverage OK");
